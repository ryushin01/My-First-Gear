/** 표에서 자기 속성만 읽는다(slug·브랜드가 "constructor" 같은 이름이어도 상속 값을 주지 않게). */
const own = (table: Readonly<Record<string, string>>, key: string): string | undefined => (Object.hasOwn(table, key) ? table[key] : undefined);

/** 상품에 영문 이름과 브랜드 영문 표기를 붙인다. 표에 없으면 붙이지 않는다. */
export function withEnglish(product: Product): Product {
  const nameEn = own(productNamesEn, product.slug);
  const brandEn = own(brandNamesEn, product.brand);
  if (!nameEn && !brandEn) return product;
  return { ...product, ...(nameEn ? { nameEn } : {}), ...(brandEn ? { brandEn } : {}) };
}
